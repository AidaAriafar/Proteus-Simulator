inline void drawChar(SDL_Renderer* renderer, char c, int x, int y, int scale)
{
    if (c >= 'a' && c <= 'z')
    {
        c = static_cast<char>(c - 'a' + 'A');
    }
    const auto& table = glyphs();
    auto it = table.find(c);
    if (it == table.end())
    {
        it = table.find('?');
    }
    const auto& rows = it->second;
    for (int row = 0; row < 7; ++row)
    {
        for (int col = 0; col < 5; ++col)
        {
            if (rows[static_cast<std::size_t>(row)][static_cast<std::size_t>(col)] == '#')
            {
                SDL_Rect rect = {x + col * scale, y + row * scale, scale, scale};
                SDL_RenderFillRect(renderer, &rect);
            }
        }
    }
}

inline void drawText(SDL_Renderer* renderer, const std::string& text, int x, int y, int scale = 1)
{
    int cursor = x;
    for (const char c : text)
    {
        drawChar(renderer, c, cursor, y, scale);
        cursor += 6 * scale;
    }
}

inline int textWidth(const std::string& text, int scale = 1)
{
    return static_cast<int>(text.size()) * 6 * scale;
}
